export type TranslationKey = LeafKeys<(typeof dictionaries)["tr"]>;

type LeafKeys<T, Prefix extends string = ""> = {
    [Key in keyof T & string]: T[Key] extends string
        ? `${Prefix}${Key}`
        : T[Key] extends Record<string, unknown>
          ? LeafKeys<T[Key], `${Prefix}${Key}.`>
          : never;
}[keyof T & string];

export function translate(
    locale: AppLocale,
    key: TranslationKey,
    values?: Record<string, string | number>
): string {
    const segments = key.split(".");
    let current: unknown = dictionaries[locale];

    for (const segment of segments) {
        if (!current || typeof current !== "object" || !(segment in current)) {
            current = undefined;
            break;
        }
        current = (current as Record<string, unknown>)[segment];
    }

    const fallback = key.split(".").reduce<unknown>((value, segment) => {
        if (!value || typeof value !== "object") return undefined;
        return (value as Record<string, unknown>)[segment];
    }, dictionaries.tr);
    const template = typeof current === "string" ? current : typeof fallback === "string" ? fallback : key;

    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) =>
        values && name in values ? String(values[name]) : match
    );
}
