export type PlayerErrorCode = (typeof PlayerErrorCode)[keyof typeof PlayerErrorCode];

export const PLAYER_ERROR_CODES: readonly PlayerErrorCode[] = Object.freeze(
    Object.values(PlayerErrorCode)
);

const PLAYER_ERROR_CODE_SET: ReadonlySet<string> = new Set(PLAYER_ERROR_CODES);

/** Values interpolated into `{name}` placeholders of the localized message. */
export type PlayerErrorParams = Readonly<Record<string, string | number>>;

export function isPlayerErrorCode(value: unknown): value is PlayerErrorCode {
    return typeof value === "string" && PLAYER_ERROR_CODE_SET.has(value);
}
